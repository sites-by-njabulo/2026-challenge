'use strict';
/* Creates the tables the first time the app connects (CREATE TABLE IF NOT EXISTS, so running it again is harmless).
   Every table gets Row Level Security switched on with no policies, so Supabase's public anon key can read and write nothing.
   The app itself connects with DATABASE_URL (the postgres role), which is not affected by Row Level Security. */
const db = require('./db');

const TABLES = ['leads', 'contacts', 'deals', 'opt_outs', 'sessions', 'settings', 'call_tally', 'call_day', 'outreach_adj', 'email_snapshots', 'login_attempts'];

const DDL = `
SELECT pg_advisory_xact_lock(7283541);
CREATE TABLE IF NOT EXISTS leads (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_name TEXT NOT NULL,
  owner_name TEXT, phone TEXT, phone_norm TEXT, email TEXT, email_norm TEXT,
  website TEXT, website_norm TEXT, city TEXT, state TEXT, trade TEXT,
  source TEXT NOT NULL DEFAULT 'other', source_link TEXT, batch TEXT, timezone TEXT, notes TEXT,
  status TEXT NOT NULL DEFAULT 'new', next_followup TEXT,
  competitor_checked TEXT, competitor_checked_date TEXT,
  opted_out INTEGER NOT NULL DEFAULT 0, opt_out_date TEXT, opt_out_channel TEXT,
  external_id TEXT, is_demo INTEGER NOT NULL DEFAULT 0, name_city_key TEXT,
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_leads_phone ON leads(phone_norm);
CREATE INDEX IF NOT EXISTS idx_leads_site ON leads(website_norm);
CREATE INDEX IF NOT EXISTS idx_leads_key ON leads(name_city_key);
CREATE INDEX IF NOT EXISTS idx_leads_status ON leads(status);
CREATE TABLE IF NOT EXISTS contacts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id INTEGER NOT NULL REFERENCES leads(id) ON DELETE CASCADE,
  channel TEXT NOT NULL, outcome TEXT NOT NULL, direction TEXT NOT NULL DEFAULT 'out',
  content TEXT, note TEXT, "at" TEXT NOT NULL, external_id TEXT, mailbox TEXT, created_at TEXT NOT NULL
);
ALTER TABLE contacts ADD COLUMN IF NOT EXISTS mailbox TEXT;
ALTER TABLE leads ADD COLUMN IF NOT EXISTS owner_odds TEXT;
ALTER TABLE leads ADD COLUMN IF NOT EXISTS owner_odds_score INTEGER;
ALTER TABLE leads ADD COLUMN IF NOT EXISTS rank_info JSONB;
CREATE INDEX IF NOT EXISTS idx_contacts_lead ON contacts(lead_id, "at");
CREATE INDEX IF NOT EXISTS idx_contacts_at ON contacts("at");
CREATE TABLE IF NOT EXISTS deals (
  lead_id INTEGER PRIMARY KEY REFERENCES leads(id) ON DELETE CASCADE,
  call_at TEXT, call_result TEXT, proposal_sent_date TEXT, deposit_paid_date TEXT,
  deposit_amount DOUBLE PRECISION, signed_date TEXT, deal_value DOUBLE PRECISION, updated_at TEXT
);
CREATE TABLE IF NOT EXISTS opt_outs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id INTEGER, business_name TEXT, phone_norm TEXT, email_norm TEXT, website_norm TEXT, name_city_key TEXT,
  "at" TEXT NOT NULL, channel TEXT NOT NULL, note TEXT, removed_at TEXT, removed_note TEXT
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY, created_at TEXT NOT NULL, expires_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT);
CREATE TABLE IF NOT EXISTS call_tally (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, day TEXT NOT NULL, dials INTEGER NOT NULL DEFAULT 0,
  conversations INTEGER NOT NULL DEFAULT 0, meetings INTEGER NOT NULL DEFAULT 0, note TEXT, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS call_day (
  day TEXT PRIMARY KEY, calls_adj INTEGER NOT NULL DEFAULT 0, reached_adj INTEGER NOT NULL DEFAULT 0,
  owner_adj INTEGER NOT NULL DEFAULT 0, good_adj INTEGER NOT NULL DEFAULT 0, verdict TEXT, updated_at TEXT
);
CREATE TABLE IF NOT EXISTS outreach_adj (day TEXT NOT NULL, key TEXT NOT NULL, adj INTEGER NOT NULL DEFAULT 0, PRIMARY KEY (day, key));
CREATE TABLE IF NOT EXISTS email_snapshots (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, taken_at TEXT NOT NULL, payload TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS login_attempts (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ip TEXT NOT NULL, at_ms BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS idx_login_attempts_ip ON login_attempts(ip, at_ms);
${TABLES.map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`).join('\n')}
`;
// the old "Contacted" stage was replaced by "Follow up" (2026-11-24); this keeps any older data in step
const FIX_OLD_STATUS = "UPDATE leads SET status = 'follow_up' WHERE status = 'contacted'";

// One cheap look first: if every table already exists with Row Level Security on, the DDL above (which takes table locks) is skipped.
const LOOK = `SELECT
  (SELECT COUNT(*) FROM pg_class c JOIN pg_namespace s ON s.oid = c.relnamespace WHERE s.nspname = 'public' AND c.relkind = 'r' AND c.relrowsecurity AND c.relname = ANY(?::text[])) AS secured,
  (SELECT COUNT(*) FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'contacts' AND column_name = 'mailbox') AS mailbox,
  (SELECT COUNT(*) FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'leads' AND column_name IN ('owner_odds', 'owner_odds_score', 'rank_info')) AS odds`;
async function provision() {
  const look = await db.get(LOOK, TABLES);
  if (!(look.secured === TABLES.length && look.mailbox === 1 && look.odds === 3)) await db.exec(DDL);
  await db.run(FIX_OLD_STATUS);
}

let ready = null;
/* Runs once per server instance (a Vercel cold start). If it fails, the next request tries again. */
function ensureSchema() {
  if (!ready) ready = provision().catch((e) => { ready = null; throw e; });
  return ready;
}
function resetSchemaFlag() { ready = null; }

module.exports = { ensureSchema, resetSchemaFlag, TABLES };
